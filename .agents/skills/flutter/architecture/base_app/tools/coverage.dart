// Runs the tests with coverage and prints the real line coverage of lib/.
//
// Run from the project root:
//   dart run tools/coverage.dart            # report only
//   dart run tools/coverage.dart --min=60   # also fail if coverage < 60%
//
// `flutter test --coverage` only reports the files some test imports, so
// files without tests are missing and the number looks better than it is.
// This script adds a temporary test that imports every file in lib/, so the
// untested ones show up with 0%, and leaves out code that has nothing to test
// (generated code, entry points, DI wiring).
import 'dart:io';

const _helperPath = 'test/coverage_helper_test.dart';
const _lcovPath = 'coverage/lcov.info';

/// Files left out of the number: generated code, l10n, entry points and DI
/// wiring. Keep this list short: anything with logic should be tested.
final List<RegExp> _excluded = [
  RegExp(r'\.(g|freezed|gr|config)\.dart$'),
  RegExp('^lib/l10n/'),
  RegExp('^lib/main.dart'),
  RegExp('^lib/main_app.dart'),
  RegExp(r'_injector\.dart$'),
  RegExp('^lib/core/icons/app_icon_name.dart'),
];

Future<void> main(List<String> args) async {
  final minArg = args
      .where((a) => a.startsWith('--min='))
      .map((a) => double.parse(a.substring('--min='.length)))
      .firstOrNull;

  _writeHelper();
  final int exitCode;
  try {
    final process = await Process.start(
      'flutter',
      ['test', '--coverage'],
      runInShell: true,
      mode: ProcessStartMode.inheritStdio,
    );
    exitCode = await process.exitCode;
  } finally {
    File(_helperPath).deleteSync();
  }
  if (exitCode != 0) {
    stderr.writeln('flutter test failed (exit $exitCode).');
    exit(exitCode);
  }

  final percent = _report();
  if (minArg != null && percent < minArg) {
    stderr.writeln(
      'Coverage ${percent.toStringAsFixed(1)}% is below the minimum $minArg%.',
    );
    exit(1);
  }
}

String _normalize(String path) => path.replaceAll(r'\', '/');

bool _isExcluded(String path) => _excluded.any((r) => r.hasMatch(path));

List<String> _libFiles() =>
    Directory('lib')
        .listSync(recursive: true)
        .whereType<File>()
        .map((f) => _normalize(f.path))
        .where((p) => p.endsWith('.dart'))
        .where((p) => !_isExcluded(p))
        // `part of` files are covered through their library.
        .where(
          (p) =>
              !File(p)
                  .readAsStringSync()
                  .contains(RegExp(r'^part of ', multiLine: true)),
        )
        .toList()
      ..sort();

void _writeHelper() {
  final package = RegExp(
    r'^name:\s*(\S+)',
    multiLine: true,
  ).firstMatch(File('pubspec.yaml').readAsStringSync())!.group(1)!;

  final imports = _libFiles()
      .map((p) => "import 'package:$package/${p.substring('lib/'.length)}';")
      .join('\n');

  File(_helperPath).writeAsStringSync('''
// GENERATED by tools/coverage.dart and deleted after the run. Do not commit.
// ignore_for_file: unused_import, directives_ordering
$imports

import 'package:flutter_test/flutter_test.dart';

void main() {
  test('every lib file is loaded for coverage', () {});
}
''');
}

/// Prints the report and returns the total percentage.
double _report() {
  final hits = <String, (int found, int hit)>{};
  String? current;
  var found = 0;
  var hit = 0;
  for (final line in File(_lcovPath).readAsLinesSync()) {
    if (line.startsWith('SF:')) {
      final path = _normalize(line.substring(3));
      current = path.substring(path.indexOf('lib/'));
    } else if (line.startsWith('LF:')) {
      found = int.parse(line.substring(3));
    } else if (line.startsWith('LH:')) {
      hit = int.parse(line.substring(3));
    } else if (line == 'end_of_record' && current != null) {
      if (!_isExcluded(current)) hits[current] = (found, hit);
      current = null;
    }
  }

  final byLayer = <String, (int, int)>{};
  var totalFound = 0;
  var totalHit = 0;
  for (final MapEntry(key: path, value: (f, h)) in hits.entries) {
    totalFound += f;
    totalHit += h;
    final layer = path.split('/').skip(1).take(2).join('/');
    final (lf, lh) = byLayer[layer] ?? (0, 0);
    byLayer[layer] = (lf + f, lh + h);
  }

  String pct(int h, int f) =>
      '${(f == 0 ? 100 : 100 * h / f).toStringAsFixed(1)}%'.padLeft(6);

  stdout.writeln('\nCoverage by folder:');
  for (final layer in byLayer.keys.toList()..sort()) {
    final (f, h) = byLayer[layer]!;
    stdout.writeln('  ${pct(h, f)}  ${'$h/$f'.padLeft(9)}  $layer');
  }

  final untested = hits.entries.where((e) => e.value.$1 > 0).toList()
    ..sort(
      (a, b) => (a.value.$2 / a.value.$1).compareTo(b.value.$2 / b.value.$1),
    );
  stdout.writeln('\nLeast covered files:');
  for (final MapEntry(key: path, value: (f, h)) in untested.take(15)) {
    stdout.writeln('  ${pct(h, f)}  ${'$h/$f'.padLeft(9)}  $path');
  }

  final percent = totalFound == 0 ? 100.0 : 100 * totalHit / totalFound;
  stdout.writeln(
    '\nTOTAL: ${percent.toStringAsFixed(1)}% '
    '($totalHit/$totalFound lines, ${hits.length} files)',
  );
  return percent;
}
